/**
 * Java Code Generator
 * Converts diagram classes + relationships into Java source files.
 */

function capitalize(s) {
  return s ? s.charAt(0).toUpperCase() + s.slice(1) : s;
}

function javaType(t) {
  if (!t) return "void";
  const map = { string: "String", boolean: "boolean", integer: "int", float: "float", double: "double", long: "long" };
  return map[t.toLowerCase()] ?? t;
}

function formatParam(p) {
  return `${javaType(p.type)} ${p.name}`;
}

export function generateJavaFiles(classes, relationships) {
  return classes.map(cls => ({
    filename: `${cls.name}.java`,
    code: generateClassCode(cls, classes, relationships),
  }));
}

function generateClassCode(cls, allClasses, relationships) {
  const lines = [];
  const outRels = relationships.filter(r => r.sourceId === cls.id);

  const inheritRel = outRels.find(r => r.type === "inheritance");
  const implRels   = outRels.filter(r => r.type === "implementation");
  const aggrRels   = outRels.filter(r => r.type === "aggregation");
  const compRels   = outRels.filter(r => r.type === "composition");

  const parentClass = inheritRel
    ? allClasses.find(c => c.id === inheritRel.targetId)
    : null;
  const implClasses = implRels
    .map(r => allClasses.find(c => c.id === r.targetId))
    .filter(Boolean);

  // Interface methods to override
  const interfaceMethods = implClasses.flatMap(ic => ic.methods.map(m => m.name));

  // Class declaration line
  let keyword = "class";
  if (cls.stereotype === "interface") keyword = "interface";
  else if (cls.stereotype === "abstract") keyword = "abstract class";
  else if (cls.stereotype === "enum") keyword = "enum";

  let decl = `public ${keyword} ${cls.name}`;
  if (parentClass) decl += ` extends ${parentClass.name}`;
  if (implClasses.length > 0) decl += ` implements ${implClasses.map(c => c.name).join(", ")}`;
  decl += " {";

  lines.push(`// Generated by UML Class Diagram Generator`);
  lines.push(``);
  lines.push(decl);

  // Enum constants
  if (cls.stereotype === "enum") {
    const consts = cls.fields.map(f => f.name.toUpperCase()).join(", ");
    lines.push(`    ${consts};`);
    lines.push(``);
    lines.push(`}`);
    return lines.join("\n");
  }

  lines.push(``);

  // Aggregated / composed class fields
  for (const rel of [...aggrRels, ...compRels]) {
    const tgt = allClasses.find(c => c.id === rel.targetId);
    if (tgt) {
      const comment = rel.type === "composition" ? "// composition" : "// aggregation";
      lines.push(`    private ${tgt.name} ${tgt.name.charAt(0).toLowerCase() + tgt.name.slice(1)}; ${comment}`);
    }
  }

  // Own fields
  for (const f of cls.fields) {
    const vis = f.visibility === "package" ? "" : f.visibility;
    const def = f.defaultValue ? ` = ${f.defaultValue}` : "";
    lines.push(`    ${vis} ${javaType(f.type)} ${f.name}${def};`);
  }

  if (cls.fields.length > 0 || aggrRels.length > 0 || compRels.length > 0) lines.push(``);

  // Constructor
  if (cls.stereotype !== "interface") {
    const params = cls.fields
      .filter(f => f.visibility === "private")
      .map(f => `${javaType(f.type)} ${f.name}`)
      .join(", ");
    lines.push(`    public ${cls.name}(${params}) {`);
    for (const f of cls.fields.filter(f => f.visibility === "private")) {
      lines.push(`        this.${f.name} = ${f.name};`);
    }
    lines.push(`    }`);
    lines.push(``);
  }

  // Methods
  for (const m of cls.methods) {
    const vis = m.visibility === "package" ? "" : m.visibility;
    const params = (m.params || []).map(formatParam).join(", ");
    const ret = javaType(m.returnType);
    const override = interfaceMethods.includes(m.name) ? "    @Override\n" : "";
    const abstractMod = (cls.stereotype === "abstract" && m.isAbstract) ? "abstract " : "";
    if (cls.stereotype === "interface" || (cls.stereotype === "abstract" && m.isAbstract)) {
      lines.push(`    ${override}    ${vis} ${abstractMod}${ret} ${m.name}(${params});`);
    } else {
      lines.push(`${override}    ${vis} ${ret} ${m.name}(${params}) {`);
      if (ret !== "void") lines.push(`        return ${defaultReturnValue(ret)};`);
      lines.push(`    }`);
    }
    lines.push(``);
  }

  lines.push(`}`);
  return lines.join("\n");
}

function defaultReturnValue(type) {
  switch (type) {
    case "int": case "long": case "float": case "double": return "0";
    case "boolean": return "false";
    case "void": return "";
    default: return "null";
  }
}
